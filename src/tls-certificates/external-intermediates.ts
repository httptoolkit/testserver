async function importP384PrivateScalar(scalar: bigint): Promise<CryptoKey> {
    const privateKey = Buffer.from(scalar.toString(16).padStart(96, '0'), 'hex');
    const ecdh = nodeCrypto.createECDH('secp384r1');
    ecdh.setPrivateKey(privateKey);
    const publicPoint = ecdh.getPublicKey(); // 0x04 || x || y

    return crypto.subtle.importKey('jwk', {
        kty: 'EC',
        crv: 'P-384',
        d: privateKey.toString('base64url'),
        x: publicPoint.subarray(1, 49).toString('base64url'),
        y: publicPoint.subarray(49).toString('base64url')
    }, { name: 'ECDSA', namedCurve: 'P-384' }, false, ['sign']);
}

